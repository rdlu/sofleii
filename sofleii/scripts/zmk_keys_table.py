#!/usr/bin/env python3
"""Generates sofleii/src/keymap/keys_table.rs from ZMK's dt-bindings/zmk/keys.h.

    python3 sofleii/scripts/zmk_keys_table.py zmk/app/include > sofleii/src/keymap/keys_table.rs

Runs the C preprocessor (`cpp`, from gcc) over keys.h, so every name gets
the value ZMK itself computes: the HID usage (page << 16 | id) with implicit
modifiers in the high byte (EXCL = LS(N1)). Stdlib only. Rerun it when a
`zmk` bump changes keys.h.
"""
import re
import subprocess
import sys

inc = sys.argv[1]
keys_h = f"{inc}/dt-bindings/zmk/keys.h"
names, deprecated = [], set()
for line in open(keys_h):
    m = re.match(r"#define ([A-Z][A-Z0-9_]*)\s", line)
    if m:
        names.append(m.group(1))
        if "DEPRECATED" in line:
            deprecated.add(m.group(1))

src = "#include <dt-bindings/zmk/keys.h>\n" + "".join(f"zmkkey_{n} {n}\n" for n in names)
out = subprocess.run(
    ["cpp", "-P", "-I", inc, "-"], input=src, capture_output=True, text=True, check=True
).stdout
values = {}
for line in out.splitlines():
    m = re.match(r"zmkkey_(\w+) (.*)", line)
    if m:
        values[m.group(1)] = eval(m.group(2), {}, {}) & 0xFFFFFFFF

# The name a value renders as: the shortest non-deprecated alias (LSHFT,
# RET, BSPC, C_VOL_UP, LBRC: what keymaps and keymap-drawer use), ties to
# the one defined first, then the overrides below.
preferred = {}
for n in names:
    if n in deprecated:
        continue
    v = values[n]
    if v not in preferred or len(n) < len(preferred[v]):
        preferred[v] = n
# Where the shortest alias isn't the usual one (GRAV, SPC, LCMD…).
OVERRIDES = """
GRAVE SPACE LGUI RGUI APOS SEMI COMMA MINUS EQUAL LCTRL RCTRL TAB HOME END
LEFT RIGHT UP DOWN C_PP C_MUTE C_NEXT C_PREV C_STOP K_APP INS PSCRN
PAUSE_BREAK CAPS PG_UP PG_DN UNDER PLUS PIPE COLON TILDE QMARK STAR DEL
ESC RET BSPC BSLH FSLH LBKT RBKT LPAR RPAR DQT LT GT EXCL AT HASH DLLR
PRCNT CARET AMPS
""".split()
for n in OVERRIDES:
    if n in values and n not in deprecated:
        preferred[values[n]] = n

print("// @generated by sofleii/scripts/zmk_keys_table.py from ZMK's")
print("// app/include/dt-bindings/zmk/keys.h (MIT, The ZMK Contributors). Do not edit.")
print()
print("/// Every keys.h name (aliases and deprecated ones too) and its value.")
print("pub const NAMES: &[(&str, u32)] = &[")
for n in names:
    print(f'    ("{n}", 0x{values[n]:08x}),')
print("];")
print()
print("/// The name each value renders as, sorted by value.")
print("pub const PREFERRED: &[(u32, &str)] = &[")
for v in sorted(preferred):
    print(f'    (0x{v:08x}, "{preferred[v]}"),')
print("];")
